-- =========================================================================
-- EQUILENS IDX: SKEMA 4 KAMAR TERISOLASI (ANTI-DUPLIKAT & RLS AMAN)
-- =========================================================================

-- KAMAR 1: MASTER EMITEN BEI (Daftar seluruh ~900+ saham & klasifikasi sektor)
CREATE TABLE IF NOT EXISTS public.master_emiten (
    ticker TEXT PRIMARY KEY,
    company_name TEXT NOT NULL,
    sector_idx TEXT NOT NULL DEFAULT 'Lainnya',
    subsector_idx TEXT DEFAULT '',
    accounting_type TEXT NOT NULL DEFAULT 'general'
        CHECK (accounting_type IN ('banking', 'commodity', 'general')),
    board TEXT DEFAULT 'Utama',
    is_active BOOLEAN NOT NULL DEFAULT true,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- KAMAR 2: FUNDAMENTAL KUARTAL (Jangkar laporan keuangan BEI & benchmark)
CREATE TABLE IF NOT EXISTS public.fundamental_kuartal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker TEXT NOT NULL REFERENCES public.master_emiten(ticker) ON DELETE CASCADE,
    period TEXT NOT NULL DEFAULT 'TTM-LATEST',
    source_type TEXT NOT NULL DEFAULT 'BEI_VERIFIED'
        CHECK (source_type IN ('BEI_VERIFIED', 'AUTO_SYNCED')),
    eps_ttm DOUBLE PRECISION,
    bvps DOUBLE PRECISION,
    ev_per_share DOUBLE PRECISION,
    ebitda_per_share DOUBLE PRECISION,
    fair_value_intrinsic DOUBLE PRECISION,
    roe DOUBLE PRECISION,
    roa DOUBLE PRECISION,
    gpm DOUBLE PRECISION,
    opm DOUBLE PRECISION,
    npm DOUBLE PRECISION,
    eps_growth_yoy DOUBLE PRECISION,
    der DOUBLE PRECISION,
    current_ratio DOUBLE PRECISION,
    quick_ratio DOUBLE PRECISION,
    interest_coverage DOUBLE PRECISION,
    altman_z DOUBLE PRECISION,
    zmijewski_x DOUBLE PRECISION,
    ocf_billion DOUBLE PRECISION,
    fcf_billion DOUBLE PRECISION,
    capex_billion DOUBLE PRECISION,
    dps DOUBLE PRECISION,
    dpr DOUBLE PRECISION,
    dividend_streak_5y INTEGER DEFAULT 0,
    sector_avg_per DOUBLE PRECISION,
    sector_avg_pbv DOUBLE PRECISION,
    sector_avg_roe DOUBLE PRECISION,
    sector_avg_der DOUBLE PRECISION,
    hist_5y_benchmark JSONB NOT NULL DEFAULT '{}'::jsonb,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_fundamental_ticker_period UNIQUE (ticker, period)
);

-- KAMAR 3: LIVE MARKET CACHE (Selalu tetap 1 baris per saham via UPSERT)
CREATE TABLE IF NOT EXISTS public.live_market_cache (
    ticker TEXT PRIMARY KEY REFERENCES public.master_emiten(ticker) ON DELETE CASCADE,
    live_price DOUBLE PRECISION NOT NULL,
    prev_close DOUBLE PRECISION,
    change_abs DOUBLE PRECISION DEFAULT 0,
    change_pct DOUBLE PRECISION DEFAULT 0,
    volume BIGINT DEFAULT 0,
    market_cap DOUBLE PRECISION,
    ma20 DOUBLE PRECISION,
    ma200 DOUBLE PRECISION,
    rsi14 DOUBLE PRECISION,
    atr_pct DOUBLE PRECISION,
    max_drawdown_1y DOUBLE PRECISION,
    support1 DOUBLE PRECISION,
    resistance1 DOUBLE PRECISION,
    quant_score INTEGER DEFAULT 50,
    verdict_status TEXT DEFAULT 'TUNGGU KOREKSI',
    primary_source TEXT NOT NULL DEFAULT 'TRADINGVIEW',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- KAMAR 4: AUDIT VALIDASI TRIPLE-CHECK (Catatan selisih antar-sumber)
CREATE TABLE IF NOT EXISTS public.audit_validasi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker TEXT NOT NULL REFERENCES public.master_emiten(ticker) ON DELETE CASCADE,
    metric_key TEXT NOT NULL,
    tv_value DOUBLE PRECISION,
    yf_value DOUBLE PRECISION,
    gf_value DOUBLE PRECISION,
    bei_value DOUBLE PRECISION,
    final_value DOUBLE PRECISION,
    spread_pct DOUBLE PRECISION DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'verified'
        CHECK (status IN ('verified', 'minor_diff', 'bei_anchor', 'failover_active')),
    checked_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_audit_ticker_metric UNIQUE (ticker, metric_key)
);

-- INDEKS KECEPATAN QUERY
CREATE INDEX IF NOT EXISTS idx_master_sector ON public.master_emiten(sector_idx);
CREATE INDEX IF NOT EXISTS idx_fund_ticker ON public.fundamental_kuartal(ticker, period);
CREATE INDEX IF NOT EXISTS idx_audit_ticker ON public.audit_validasi(ticker);

-- KEAMANAN ROW LEVEL SECURITY (Baca publik aman, tulis dikunci khusus Backend Service Role)
ALTER TABLE public.master_emiten ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.fundamental_kuartal ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.live_market_cache ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.audit_validasi ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public read master_emiten" ON public.master_emiten;
CREATE POLICY "Public read master_emiten" ON public.master_emiten FOR SELECT USING (true);

DROP POLICY IF EXISTS "Public read fundamental_kuartal" ON public.fundamental_kuartal;
CREATE POLICY "Public read fundamental_kuartal" ON public.fundamental_kuartal FOR SELECT USING (true);

DROP POLICY IF EXISTS "Public read live_market_cache" ON public.live_market_cache;
CREATE POLICY "Public read live_market_cache" ON public.live_market_cache FOR SELECT USING (true);

DROP POLICY IF EXISTS "Public read audit_validasi" ON public.audit_validasi;
CREATE POLICY "Public read audit_validasi" ON public.audit_validasi FOR SELECT USING (true);
